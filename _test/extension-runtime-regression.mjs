import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const helperPath = join(root, "extension", "tool-runtime.js")
const helperSource = await readFile(helperPath, "utf8")

// Import the browser ESM helper as a data URL so this test does not require an
// extension/package.json solely to tell Node that .js is an ES module.
const helperUrl = `data:text/javascript;base64,${Buffer.from(helperSource).toString("base64")}`
const { aggregateTransactionCompletion, buildPageEvaluationExpression, isTransientContentErrorMessage } = await import(helperUrl)
const { getModifierMask, getPrintableKeyDescriptor, getPrimaryModifier, normalizeCdpInputMode } = await import(new URL("../extension/cdp-input.js", import.meta.url))
const { makeToolContent } = await import(new URL("../host/src/mcp-server.js", import.meta.url))
const { TOOLS } = await import(new URL("../host/src/tools.meta.js", import.meta.url))

assert.equal(isTransientContentErrorMessage("The page moved into back/forward cache, message channel closed."), true)
assert.equal(isTransientContentErrorMessage("Could not establish connection. Receiving end does not exist."), true)
assert.equal(isTransientContentErrorMessage("SyntaxError: invalid selector"), false)
assert.equal(aggregateTransactionCompletion([{ action: "wait", completionLevel: "observed" }]), "observed")
assert.equal(aggregateTransactionCompletion([{ action: "click", completionLevel: "dispatched" }]), "dispatched")
assert.equal(aggregateTransactionCompletion([{ action: "fill", completionLevel: "applied" }, { action: "reload", completionLevel: "committed" }]), "applied")
assert.equal(aggregateTransactionCompletion([{ action: "click", completionLevel: "committed" }, { action: "navigate", completionLevel: "committed" }]), "committed")
assert.equal(aggregateTransactionCompletion([{ action: "click", completionLevel: "committed" }], { index: 1, error: "failed" }), "partial")
assert.deepEqual(getPrintableKeyDescriptor("3"), { key: "3", code: "Digit3", windowsVirtualKeyCode: 51, modifiers: 0 })
assert.deepEqual(getPrintableKeyDescriptor("A"), { key: "A", code: "KeyA", windowsVirtualKeyCode: 65, modifiers: 8 })
assert.equal(getPrintableKeyDescriptor("杨"), null)
assert.equal(normalizeCdpInputMode("keyEvents"), "keyEvents")
assert.equal(normalizeCdpInputMode("anything-else"), "insertText")
assert.equal(getPrimaryModifier("MacIntel").key, "Meta")
assert.equal(getPrimaryModifier("Win32").key, "Control")
assert.equal(getModifierMask(["Meta", "Shift", "Meta"]), 12)
const transactionTool = TOOLS.find((tool) => tool.name === "omeety_act_and_verify")
assert.equal(transactionTool.inputSchema.properties.steps.maxItems, 20)
assert.equal(transactionTool.inputSchema.properties.tabId.type, "integer")
assert.equal(TOOLS.find((tool) => tool.name === "omeety_execute_js").inputSchema.properties.tabId.type, "integer")
assert.equal(TOOLS.find((tool) => tool.name === "omeety_wait_for").inputSchema.properties.tabId.type, "integer")
assert.equal(TOOLS.find((tool) => tool.name === "omeety_browser_transaction").inputSchema.properties.steps.maxItems, 20)
assert.equal(TOOLS.find((tool) => tool.name === "omeety_browser_observe").inputSchema.properties.deep.type, "boolean")
assert.equal(TOOLS.find((tool) => tool.name === "omeety_browser_observe").inputSchema.properties.profile.default, "compact")
assert.equal(TOOLS.find((tool) => tool.name === "omeety_browser_act").inputSchema.properties.expect.properties.persistAfterReload.type, "boolean")

const success = await eval(buildPageEvaluationExpression("return { answer: await Promise.resolve(42) }"))
assert.deepEqual(success, { ok: true, value: '{"answer":42}' })

const failure = await eval(buildPageEvaluationExpression('throw new Error("expected failure")'))
assert.equal(failure.ok, false)
assert.match(failure.error, /expected failure/)

const imageContent = makeToolContent({
  title: "context bundle",
  screenshot: { dataUrl: "data:image/jpeg;base64,aGVsbG8=", width: 10 },
})
assert.equal(imageContent.length, 2)
assert.equal(imageContent[0].type, "text")
assert.doesNotMatch(imageContent[0].text, /base64,aGVsbG8=/)
assert.deepEqual(imageContent[1], { type: "image", mimeType: "image/jpeg", data: "aGVsbG8=" })

